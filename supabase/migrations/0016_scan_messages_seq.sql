-- 0016: deterministic chat message ordering.
--
-- A question/answer pair is inserted in one statement, so both rows get the
-- same created_at (now() is stable within a transaction) and id is
-- gen_random_uuid() — random, not monotonic. Ordering by (created_at, id)
-- can therefore flip the pair both in the UI and in the history sent to the
-- LLM. `seq` is a monotonically increasing insert-order column; all reads
-- order by it.

alter table scan_messages
  add column seq bigint generated by default as identity;

-- Backfill existing rows in their best-known order. The identity default
-- assigned values in physical row order during the rewrite; re-number by
-- (created_at, id) so historical ordering is at least stable.
with ordered as (
  select id, row_number() over (order by created_at, id) as rn
  from scan_messages
)
update scan_messages m
set seq = o.rn
from ordered o
where m.id = o.id;

-- Move the identity sequence past the backfilled values.
select setval(
  pg_get_serial_sequence('scan_messages', 'seq'),
  coalesce((select max(seq) from scan_messages), 0) + 1,
  false
);

alter table scan_messages
  alter column seq set not null;

drop index if exists scan_messages_scan_created_idx;
create index scan_messages_scan_seq_idx
  on scan_messages(scan_id, seq);
